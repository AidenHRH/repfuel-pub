// Builds src/data/exerciseGuides.ts from Free Exercise DB (https://github.com/yuhonas/free-exercise-db, Unlicense)
// and the hand-made match table scripts/exercise-guide-matches.json (RepFuel exercise name → Free Exercise DB id,
// or null for no good match). Run: node scripts/build-exercise-guides.js <path to exercises.json>
const fs = require('fs');
const path = require('path');

const source = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const byId = new Map(source.map((e) => [e.id, e]));
const matches = JSON.parse(fs.readFileSync(path.join(__dirname, 'exercise-guide-matches.json'), 'utf8'));
// Same as exerciseId() in src/database/seed/exercises.ts.
const exerciseId = (name) =>
  `ex_${name
    .toLowerCase()
    .replace(/[’']/g, '')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '')}`;

const guides = {};
const unmatched = [];
for (const [name, sourceId] of Object.entries(matches)) {
  if (sourceId === null) {
    unmatched.push(exerciseId(name));
    continue;
  }
  const e = byId.get(sourceId);
  if (!e) throw new Error(`No Free Exercise DB entry ${sourceId} (for ${name})`);
  guides[exerciseId(name)] = { sourceId, steps: e.instructions, primaryMuscles: e.primaryMuscles, images: e.images };
}

const out = `// Generated by scripts/build-exercise-guides.js from Free Exercise DB (Unlicense). Do not edit by hand.
import type { ExerciseGuide } from '@/domain/howTo';

export const EXERCISE_GUIDES: Record<string, ExerciseGuide> = ${JSON.stringify(guides, null, 2)};

/** Built-in exercises with no good match: they show "No guide for this one yet". */
export const UNMATCHED: string[] = ${JSON.stringify(unmatched, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'exerciseGuides.ts'), out);
console.log(`${Object.keys(guides).length} guides, ${unmatched.length} unmatched`);
